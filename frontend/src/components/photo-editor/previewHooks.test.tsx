import { act, renderHook } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { loadPhotoPreview, renderPhotoPreview } from '@/api/imageEdit'
import { DEFAULT_EDITS } from '@/utils/imageEdit'
import { decodePhoto, type PhotoResource } from './imageResource'
import { usePhotoResource } from './usePhotoResource'
import { PREVIEW_DEBOUNCE_MS, useServerPreview } from './useServerPreview'
vi.mock('@/api/imageEdit', () => ({ getPreviewSourceSize: vi.fn(() => undefined), getPreviewSourceHash: vi.fn(() => 'a'.repeat(64)), loadPhotoPreview: vi.fn(), renderPhotoPreview: vi.fn(), imageErrorMessage: vi.fn(async () => '网络连接失败') }))
vi.mock('./imageResource', () => ({ decodePhoto: vi.fn() }))
const blob = new Blob(['jpeg'], { type: 'image/jpeg' })
const resource = (): PhotoResource => ({ image: {} as ImageBitmap, width: 517, height: 606, dispose: vi.fn() })
function pending<T>() { let resolve!: (value: T) => void; const promise = new Promise<T>(r => { resolve = r }); return { promise, resolve } }
beforeEach(() => { vi.clearAllMocks(); vi.useFakeTimers() })
afterEach(() => vi.useRealTimers())

it('ignores old photo responses and aborts requests on switching and unmount', async () => {
  const old = pending<Blob>(), next = pending<Blob>(), image = resource()
  vi.mocked(loadPhotoPreview).mockReturnValueOnce(old.promise).mockReturnValueOnce(next.promise)
  vi.mocked(decodePhoto).mockResolvedValue(image)
  const hook = renderHook(({ id }) => usePhotoResource(id), { initialProps: { id: 1 } })
  const signal = vi.mocked(loadPhotoPreview).mock.calls[0][1]
  hook.rerender({ id: 2 })
  expect(signal.aborted).toBe(true)
  await act(async () => { next.resolve(blob) })
  expect(hook.result.current.resource).toBe(image)
  await act(async () => { old.resolve(blob) })
  expect(hook.result.current.photoId).toBe(2)
  expect(decodePhoto).toHaveBeenCalledTimes(1)
  hook.unmount()
  expect(image.dispose).toHaveBeenCalledOnce()
})
it('closes a bitmap that finishes decoding after its photo was abandoned', async () => {
  const decoding = pending<PhotoResource>(), late = resource()
  vi.mocked(loadPhotoPreview).mockResolvedValue(blob)
  vi.mocked(decodePhoto).mockReturnValueOnce(decoding.promise).mockResolvedValueOnce(resource())
  const hook = renderHook(({ id }) => usePhotoResource(id), { initialProps: { id: 1 } })
  await act(async () => {})
  hook.rerender({ id: 2 })
  await act(async () => { decoding.resolve(late) })
  expect(late.dispose).toHaveBeenCalledOnce()
  expect(hook.result.current.photoId).toBe(2)
})
it('retries base loading after errors without leaking resources', async () => {
  const image = resource()
  vi.mocked(loadPhotoPreview).mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce(blob)
  vi.mocked(decodePhoto).mockResolvedValue(image)
  const hook = renderHook(() => usePhotoResource(1))
  await act(async () => {})
  expect(hook.result.current.error).toBe('网络连接失败')
  await act(async () => { hook.result.current.retry() })
  expect(hook.result.current.resource).toBe(image)
})
it('debounces edits, aborts stale server calls and accepts only latest parameters', async () => {
  const first = pending<Blob>(), second = pending<Blob>(), base = resource(), latest = resource()
  vi.mocked(renderPhotoPreview).mockReturnValueOnce(first.promise).mockReturnValueOnce(second.promise)
  vi.mocked(decodePhoto).mockResolvedValue(latest)
  const hook = renderHook(({ value }) => useServerPreview(1, { ...DEFAULT_EDITS, exposure_ev: value }, base), { initialProps: { value: 0.5 } })
  await act(async () => { await vi.advanceTimersByTimeAsync(PREVIEW_DEBOUNCE_MS - 1) })
  expect(renderPhotoPreview).not.toHaveBeenCalled()
  await act(async () => { await vi.advanceTimersByTimeAsync(1) })
  const signal = vi.mocked(renderPhotoPreview).mock.calls[0][2]
  hook.rerender({ value: 1 })
  expect(signal.aborted).toBe(true)
  await act(async () => { first.resolve(blob) })
  expect(hook.result.current.resource).toBeUndefined()
  await act(async () => { await vi.advanceTimersByTimeAsync(PREVIEW_DEBOUNCE_MS); second.resolve(blob) })
  expect(hook.result.current.resource).toBe(latest)
  hook.unmount()
  expect(latest.dispose).toHaveBeenCalledOnce()
})
it('keeps edits through server errors and retry sends the same snapshot', async () => {
  const edit = { ...DEFAULT_EDITS, contrast: 35 }, base = resource()
  vi.mocked(renderPhotoPreview).mockRejectedValue(new Error('offline'))
  const hook = renderHook(() => useServerPreview(9, edit, base))
  await act(async () => { await vi.advanceTimersByTimeAsync(PREVIEW_DEBOUNCE_MS) })
  expect(hook.result.current.status).toBe('error')
  act(() => hook.result.current.retry())
  await act(async () => { await vi.advanceTimersByTimeAsync(PREVIEW_DEBOUNCE_MS) })
  expect(vi.mocked(renderPhotoPreview).mock.calls.map(call => call[1])).toEqual([edit, edit])
})
it('never revives a disposed preview when undo returns to the same parameter key', async () => {
  const base = resource(), first = resource()
  vi.mocked(renderPhotoPreview).mockResolvedValue(blob)
  vi.mocked(decodePhoto).mockResolvedValue(first)
  const hook = renderHook(({ value }) => useServerPreview(1, { ...DEFAULT_EDITS, exposure_ev: value }, base), { initialProps: { value: 0.7 } })
  await act(async () => { await vi.advanceTimersByTimeAsync(PREVIEW_DEBOUNCE_MS) })
  expect(hook.result.current.resource).toBe(first)
  hook.rerender({ value: 1 })
  expect(first.dispose).toHaveBeenCalledOnce()
  hook.rerender({ value: 0.7 })
  expect(hook.result.current.resource).toBeUndefined()
  expect(hook.result.current.status).toBe('waiting')
  hook.unmount()
})
it('rejects outdated geometry preview responses even with identical color parameters',async()=>{
  const first=pending<Blob>(),second=pending<Blob>(),base=resource(),latest=resource()
  vi.mocked(renderPhotoPreview).mockReturnValueOnce(first.promise).mockReturnValueOnce(second.promise)
  vi.mocked(decodePhoto).mockResolvedValue(latest)
  const hook=renderHook(({q})=>useServerPreview(1,{...DEFAULT_EDITS,schema_version:2,geometry:{rotation_quadrants:q,flip_horizontal:false,flip_vertical:false,crop:null}},base),{initialProps:{q:1}})
  await act(async()=>{await vi.advanceTimersByTimeAsync(PREVIEW_DEBOUNCE_MS)})
  hook.rerender({q:2})
  await act(async()=>{first.resolve(blob)})
  expect(hook.result.current.resource).toBeUndefined()
  await act(async()=>{await vi.advanceTimersByTimeAsync(PREVIEW_DEBOUNCE_MS);second.resolve(blob)})
  expect(hook.result.current.resource).toBe(latest)
  expect(vi.mocked(renderPhotoPreview).mock.calls[1][1]).toMatchObject({schema_version:2,geometry:{rotation_quadrants:2}})
  hook.unmount()
})
